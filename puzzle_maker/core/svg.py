"""SVG output for jigsaw puzzles.

The puzzle is emitted as a **single** ``<path>`` element with one
subpath per cut line. That matters for Rayforge: its SVG importer turns
one path element into one workpiece, so the whole puzzle arrives as a
single item the user can drop a Contour step on.

Physical units are written as ``width="200mm"`` plus a matching
``viewBox``, so the import lands at the intended size.
"""

from __future__ import annotations

from pathlib import Path as FsPath
from typing import Sequence

from .geometry import Path
from .jigsaw import PuzzleParams, generate

__all__ = [
    "DEFAULT_STROKE_MM",
    "paths_to_svg",
    "puzzle_to_svg",
    "write_puzzle_svg",
]

#: A hairline. Rayforge cuts along the path centre line, so the value is
#: cosmetic, but 0.1 mm is what its own exporters use.
DEFAULT_STROKE_MM = 0.1


def paths_to_svg(
    paths: Sequence[Path],
    width_mm: float,
    height_mm: float,
    *,
    stroke_mm: float = DEFAULT_STROKE_MM,
    color: str = "#000000",
    precision: int = 3,
) -> str:
    """Serialize *paths* into a standalone SVG document string."""
    if not paths:
        raise ValueError("Cannot export an empty puzzle.")
    if width_mm <= 0 or height_mm <= 0:
        raise ValueError("SVG width and height must be positive.")

    # SVG has Y pointing down, the generator uses Y up; flip so the
    # document looks the same in every viewer and in Rayforge.
    data = " ".join(
        path.flipped_y(height_mm).to_svg(precision) for path in paths
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<svg xmlns="http://www.w3.org/2000/svg" version="1.1" '
        f'width="{width_mm:.3f}mm" height="{height_mm:.3f}mm" '
        f'viewBox="0 0 {width_mm:.3f} {height_mm:.3f}">\n'
        "  <!-- Generated by Puzzle Maker, a Rayforge addon -->\n"
        f'  <path d="{data}" fill="none" stroke="{color}" '
        f'stroke-width="{stroke_mm:g}" />\n'
        "</svg>\n"
    )


def puzzle_to_svg(
    params: PuzzleParams,
    *,
    stroke_mm: float = DEFAULT_STROKE_MM,
    color: str = "#000000",
    precision: int = 3,
) -> str:
    """Generate a puzzle and return it as an SVG document string."""
    puzzle = generate(params)
    return paths_to_svg(
        puzzle.all(),
        params.width_mm,
        params.height_mm,
        stroke_mm=stroke_mm,
        color=color,
        precision=precision,
    )


def write_puzzle_svg(
    target: str | FsPath,
    params: PuzzleParams,
    *,
    stroke_mm: float = DEFAULT_STROKE_MM,
    color: str = "#000000",
) -> FsPath:
    """Write a puzzle SVG to *target* and return the path."""
    target = FsPath(target)
    target.write_text(
        puzzle_to_svg(params, stroke_mm=stroke_mm, color=color),
        encoding="utf-8",
    )
    return target
